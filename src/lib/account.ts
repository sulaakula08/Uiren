import "server-only";
import { cache } from "react";
import { db } from "./db";

/**
 * Профиль пользователя — один запрос в базу на один HTTP-запрос.
 *
 * Макет и страница проверяют роль независимо друг от друга, а макет вдобавок
 * спрашивал, пройден ли тур: на каждую страницу приходилось три одинаковых
 * чтения одной и той же строки, идущих последовательно. При базе в другом
 * регионе это сотни миллисекунд впустую ещё до первого полезного запроса.
 *
 * cache() из React живёт ровно один запрос, поэтому кешировать здесь нечего
 * бояться: следующий запрос снова прочитает актуальные данные.
 */
export const loadAccount = cache(async (userId: string) =>
  db.user.findUnique({
    where: { id: userId },
    select: { id: true, role: true, tourDoneAt: true },
  }),
);
